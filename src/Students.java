
public class Students {
    Integer NPM;
    String Fullname;
    String ClassName;
    Integer Semester;
    Float GPA;

    public void setNPM(Integer npm) {
        NPM = npm;
    }

    public void setFullname(String fullname) {
        Fullname = fullname;
    }

    public void setClassName(String className) {
        ClassName = className;
    }

    public void setSemester(Integer semester) {
        Semester = semester;
    }

    public void setGPA(Float gpa) {
        GPA = gpa;
    }
}
